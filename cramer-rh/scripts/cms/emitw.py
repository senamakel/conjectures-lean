import json, sys, os
sys.path.insert(0,'gen')
d=json.load(open(sys.argv[1])); outdir=sys.argv[2]; W=int(sys.argv[3]); limit=int(sys.argv[4]) if len(sys.argv)>4 else None
ents=d['ents']
# final entry carries the previous cell's Gn/en so the extra TV transition is zero
ents[-1]['Gn']=ents[-2]['Gn']; ents[-1]['en']=ents[-2]['en']; ents[-1]['r']=ents[-2]['r']
C1a,C1b,C2a,C2b,As=d['C']; GD=d['GD']
def ent(e): return f"⟨{e['N']}, {e['k']}, {e['cl']}, {e['cu']}, {e['j']}, {e['fl']}, {e['tg']}, {e['Gn']}, {e['en']}, {e['r']}⟩"
def ps(w,f): return sum(f(w[i],w[i+1]) for i in range(len(w)-1))
fs=dict(
 a1G=lambda e,f: e['Gn']*(f['N']-e['N']), a1e=lambda e,f: e['en']*(f['N']-e['N']),
 a2Gp=lambda e,f: e['Gn']*(f['N']-e['N'])*e['r'] if e['r']>=0 else 0,
 a2Gn=lambda e,f: 0 if e['r']>=0 else e['Gn']*(f['N']-e['N'])*(-e['r']),
 a2ep=lambda e,f: e['en']*(f['N']-e['N'])*e['r'] if e['r']>=0 else 0,
 a2en=lambda e,f: 0 if e['r']>=0 else e['en']*(f['N']-e['N'])*(-e['r']),
 tvG=lambda e,f: abs(f['Gn']-e['Gn']), tve=lambda e,f: abs(f['en']-e['en']))
os.makedirs(outdir,exist_ok=True)
q=f"/-! Coefficients of `Q` (generated by `scripts/cms_gen.py`). -/\n\nimport CramerCompute.CMSCheck\n\nnamespace CramerCompute.CMSData\n\n"
open(os.path.join(outdir,'Q.lean'),'w').write(f"import CramerCompute.CMSCheck\n\n/-! Coefficients of `Q` and constants of the weight (generated by `scripts/cms_gen.py`). -/\n\nnamespace CramerCompute.CMSData\n\ndef qs : List Int := {d['qs']}\n\nend CramerCompute.CMSData\n")
wins=[]
i=0
while i < len(ents)-1:
    wins.append(ents[i:i+W+1]); i+=W
tot={k:0 for k in fs}
names=[]
for k,w in enumerate(wins):
    if limit is not None and k>=limit: break
    v={key:ps(w,f) for key,f in fs.items()}
    for key in tot: tot[key]+=v[key]
    nm=f"w{k:04d}"; names.append(nm)
    body=",\n  ".join(ent(e) for e in w)
    vs="⟨"+", ".join(str(v[key]) for key in ['a1G','a1e','a2Gp','a2Gn','a2ep','a2en','tvG','tve'])+"⟩"
    src=f"""import CramerCompute.CMSData.Q

/-! Cell window {k} (generated by `scripts/cms_gen.py`). -/

namespace CramerCompute.CMSData

def {nm} : List Ent := [
  {body}]

set_option maxRecDepth 100000 in
theorem {nm}_ok : winOK qs {GD} {C1a} {C1b} {C2a} {C2b} {nm} {vs} = true := by decide +kernel

theorem {nm}_head : {nm}.head? = some {ent(w[0])} := rfl

theorem {nm}_last : {nm}.getLast? = some {ent(w[-1])} := rfl

end CramerCompute.CMSData
"""
    open(os.path.join(outdir,f"W{k:04d}.lean"),'w').write(src)
json.dump(dict(names=names,tot=tot,nwin=len(wins)),open(os.path.join(sys.argv[1]+'.wins.json'),'w'))
print('windows',len(wins),'written',len(names),'tot',tot)
