import json, math, sys
NN=10**6; KK=10**15; KC=10**9; PIL=3141592; PIH=3141593
sol=json.load(open(sys.argv[1]))
maj=[(math.ceil(v*KC), round(s*NN), round(t*NN)) for s,t,v in sol]
def lfl(S,T,X): return KK*S*S//(S*S+(X-T)**2)
def rhs(X0,X1):
  r=0
  for C,S,T in maj:
    r+=C*(min(lfl(S,T,X0),lfl(S,T,X1))+min(lfl(S,-T,X0),lfl(S,-T,X1)))
  return r
def T10n(M): return 3628800*NN**10-1814400*M**2*NN**8+151200*M**4*NN**6-5040*M**6*NN**4+90*M**8*NN**2-M**10
T10d=3628800*NN**10
def T8n(m): return 40320*NN**8-20160*m**2*NN**6+1680*m**4*NN**4-56*m**6*NN**2+m**8
T8d=40320*NN**8
def tlo(X0,k): return 2*X0-k*PIH
def thi(X1,k): return 2*X1-k*PIL
def tmax(X0,X1,k): return max(abs(tlo(X0,k)),abs(thi(X1,k)))
def tmin(X0,X1,k):
  if tlo(X0,k)<=0<=thi(X1,k): return 0
  return min(abs(tlo(X0,k)),abs(thi(X1,k)))
def omcN(X0,X1,k): return T10d-T10n(tmax(X0,X1,k)) if k%2==0 else T8d+T8n(tmin(X0,X1,k))
def omcD(k): return T10d if k%2==0 else T8d
def ok(X0,X1,tag,k):
  R=rhs(X0,X1)
  if not X0<=X1: return False
  if tag==0: return 0<X0 and 802*NN**2*KK*KC<=800*X0**2*R
  if tag==1:
    Wn=1200*NN+801*X1; Wd=639200*NN; P=omcN(X0,X1,k); Q=omcD(k)
    return 0<X0 and tmax(X0,X1,k)<=3*NN and Wn<=Wd and (P*Wd**2+Q*Wn*Wd+Q*Wn**2)*KK*KC*NN**2<=2*X0**2*R*Q*Wd**2
  Tpn=120*NN**4+X0**4-20*X0**2*NN**2
  return X1<=NN and 800*(Tpn**2*638401*NN+(799*NN+3200*X1)*14400*NN**8)*KK*KC<=799*14400*NN**8*638401*NN*R
def bestk(X0,X1): return max(0,round((X0+X1)/PIH))
XEND=int(float(sys.argv[2])*NN)
cells=[]; X=0; w=10000
while X<XEND:
  w=min(w*2, max(1000, X//20), XEND-X)
  while True:
    X1=X+w; k=bestk(X,X1)
    tags=[2,1,0] if X1<=NN else [1,0]
    t=next((t for t in tags if ok(X,X1,t,k)),None)
    if t is not None: break
    w//=2
    if w<1: print("FAIL at",X); sys.exit(1)
  cells.append((X,X1,t,k)); X=X1
print(len(cells), file=sys.stderr)
json.dump({"maj":maj,"cells":cells},open(sys.argv[3],'w'))
