"""Write the chunk modules LLS/Compute2/C2_*.lean and LLS/Bach2/Finite2.lean (Bach's constant 2).

Each chunk is one `native_decide` evaluating `LLS.Check.checkChunk m w lo hi`
(soundness: `LLS.Check.checkChunk_sound`). Run from the repository root.
"""
P = 2 ** 20
chunks = [
    (1024, 10, 3, 2**17), (1024, 10, 2**17, 2**18), (1024, 10, 2**18, 2**19),
    (1024, 10, 2**19, 2**20), (1024, 10, 2**20, 2**21), (1024, 10, 2**21, 3 * P),
    (1024, 10, 3 * P, 2**22), (1024, 10, 2**22, 6 * P), (1024, 10, 6 * P, 2**23),
    (1024, 10, 2**23, 2**24), (1024, 10, 2**24, 2**25), (1024, 10, 2**25, 2**26),
    (1024, 10, 2**26, 2**27), (1024, 4, 2**27, 2**100), (64, 0, 2**100, 2**2500),
]
def lit(n):
    for k in range(1, 3000):
        if n == 2**k: return f"2 ^ {k}"
    return str(n)
for i, (m, w, lo, hi) in enumerate(chunks):
    open(f"LLS/Compute2/C2_{i}.lean", "w").write(f"""import LLSCheck

/-! Chunk {i} of the finite computation for Bach's constant `2`: `{lit(lo)} ≤ q < {lit(hi)}`.

Evaluated by `native_decide` (one auxiliary axiom trusting the compiled evaluation of the
core-Lean checker `LLSCheck`; soundness `LLS.Check.checkChunk_sound`). Generated by
`scripts/emit_chunks2.py`. -/

namespace LLS

theorem chunk2_ok_{i} : LLS.Check.checkChunk {m} {w} ({lit(lo)}) ({lit(hi)}) = true := by
  native_decide

end LLS
""")
imports = "\n".join(f"import LLS.Compute2.C2_{i}" for i in range(len(chunks)))
body = ""
for i, (m, w, lo, hi) in enumerate(chunks[:-1]):
    body += f"  rcases lt_or_ge q ({lit(hi)}) with h | h\n  · exact LLS.Check.checkChunk_sound chunk2_ok_{i} q (by omega) h\n"
m, w, lo, hi = chunks[-1]
body += f"  exact LLS.Check.checkChunk_sound chunk2_ok_{len(chunks)-1} q h hq\n"
open("LLS/Bach2/Finite2.lean", "w").write(f"""import LLS.Bach2.Sound
{imports}

/-!
# The checked range `3 ≤ q < 2^2500` for Bach's constant `2`

The {len(chunks)} chunks of `LLS/Compute2/`, glued by `LLS.Check.checkChunk_sound`. Generated by
`scripts/emit_chunks2.py`.
-/

set_option exponentiation.threshold 4096

namespace LLS

theorem good2_range (q : ℕ) (hq3 : 3 ≤ q) (hq : q < 2 ^ 2500) : Good2 q := by
{body}
end LLS
""")
