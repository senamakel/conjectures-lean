#!/usr/bin/env python3
"""Generate Grosswald/Run/ (Algorithm 1 chunks for p > 10^13) and Grosswald/Covered.lean from a
cut of the tree produced by scripts/treecut.c:

    N n cost          root of ω(p-1) = n
    S q ... E         split on q: subtree with q ∈ X, then subtree with q ∈ Y
    C n cost X Y      a chunk: `checkNode n 40 X Y = true` by native_decide

Usage: gen_tree.py cut.txt [BIN]   (BIN: max estimated candidates per module, default 4e8)
"""
import os, sys, re
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'Grosswald')
lines = [l.split(None, 3) if l.startswith('C') else l.split() for l in open(sys.argv[1]) if l.strip()]
BIN = float(sys.argv[2]) if len(sys.argv) > 2 else 4e8
pos = 0
chunks = []   # (n, cost, X, Y)
def parse():
    global pos
    l = lines[pos]; pos += 1
    if l[0] == 'C':
        n, cost, rest = int(l[1]), float(l[2]), l[3]
        X, Y = re.findall(r'\[[^\]]*\]', rest)
        chunks.append((n, cost, X, Y))
        return ('C', len(chunks) - 1)
    assert l[0] == 'S', l
    q = int(l[1]); a = parse(); b = parse()
    assert lines[pos][0] == 'E'; pos += 1
    return ('S', q, a, b)
roots = {}
while pos < len(lines):
    l = lines[pos]; pos += 1
    assert l[0] == 'N'
    roots[int(l[1])] = parse()
# bin-pack chunks into modules
mods = []; cur = []; cc = 0
for i, (n, cost, X, Y) in enumerate(chunks):
    if cur and cc + cost > BIN:
        mods.append(cur); cur = []; cc = 0
    cur.append(i); cc += cost
if cur: mods.append(cur)
modof = {}
os.makedirs(f'{ROOT}/Run', exist_ok=True)
for f in os.listdir(f'{ROOT}/Run'):
    os.remove(f'{ROOT}/Run/{f}')
for m, idxs in enumerate(mods):
    body = ''.join(f'theorem c{i:05d} : checkNode {chunks[i][0]} 40 {chunks[i][2]} {chunks[i][3]} = true := by\n  native_decide\n'
                   for i in idxs)
    for i in idxs: modof[i] = m
    est = sum(chunks[i][1] for i in idxs)
    open(f'{ROOT}/Run/M{m:04d}.lean', 'w').write(f'''import Grosswald.Alg

/-! Verified computation (`native_decide`): Algorithm 1 subtrees, about {est:.2e} enumerated `k`
in all. Soundness: `Grosswald.Alg.checkNode_sound`. Generated by `scripts/gen_tree.py`. -/

namespace Grosswald.Run
open Grosswald.Alg

{body}
end Grosswald.Run
''')
def term(t):
    if t[0] == 'C':
        return f'(covered_of_check Run.c{t[1]:05d})'
    return f'(covered_split {t[1]} {term(t[2])} {term(t[3])})'
imps = ''.join(f'import Grosswald.Run.M{m:04d}\n' for m in range(len(mods)))
defs = ''
for n in sorted(roots):
    defs += f'theorem covered_{n} : Covered {n} [2] [] :=\n  {term(roots[n])}\n\n'
cases = '\n'.join(f'  · exact covered_{n}' for n in sorted(roots))
open(f'{ROOT}/Covered.lean', 'w').write(f'''import Grosswald.Alg
{imps}
/-!
# Algorithm 1 for every `n = ω(p - 1) ≤ 30` (primes `p > 10^13`)

Each root `(n, [2], [])` is split (`covered_split`) down to the subtrees evaluated in
`Grosswald/Run/`. Generated by `scripts/gen_tree.py`.
-/

namespace Grosswald
open Alg

/-- The primes of a node all have a small prime primitive root (given `NoSieve`). -/
def Covered (n : ℕ) (X Y : List ℕ) : Prop :=
  ∀ p, InClass n X Y p → NoSieve p → HasSmallPrimePrimitiveRoot p

lemma covered_of_check {{n : ℕ}} {{X Y : List ℕ}} (h : checkNode n 40 X Y = true) : Covered n X Y :=
  checkNode_sound n 40 X Y h

lemma covered_split {{n : ℕ}} {{X Y : List ℕ}} (q : ℕ) (h1 : Covered n (q :: X) Y)
    (h2 : Covered n X (q :: Y)) : Covered n X Y := by
  intro p ⟨hpr, hbig, hn, hX, hY⟩ hns
  by_cases hq : q ∣ p - 1
  · refine h1 p ⟨hpr, hbig, hn, fun r hr => ?_, hY⟩ hns
    rcases List.mem_cons.mp hr with h | h
    · rw [h]; exact hq
    · exact hX r h
  · refine h2 p ⟨hpr, hbig, hn, hX, fun r hr => ?_⟩ hns
    rcases List.mem_cons.mp hr with h | h
    · rw [h]; exact hq
    · exact hY r h

{defs}lemma covered_root {{n : ℕ}} (h1 : 1 ≤ n) (h30 : n ≤ 30) : Covered n [2] [] := by
  interval_cases n
{cases}

end Grosswald
''')
print(len(chunks), 'chunks in', len(mods), 'modules; est total %.3e' % sum(c[1] for c in chunks))
