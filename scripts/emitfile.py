import sys
from emit import *
c=F(sys.argv[1]); lo=int(sys.argv[2]); hi=int(sys.argv[3]); cstr=sys.argv[4]; tag=sys.argv[5]
ivs=plan2(c,2**lo,2**hi)
out=[f"""import LLS.Numerics.Good

/-!
# Certified intervals for `c = {cstr}`: every `2^{lo} ≤ q < 2^{hi}` is `GoodQ`

Generated by `scripts/emitfile.py {sys.argv[1]} {lo} {hi}`; {len(ivs)} intervals. Each certificate is checked
by `decide +kernel` (integer power comparisons) and `norm_num` (rational arithmetic).
-/

namespace LLS.Iv{tag}
open LLS
"""]
for i,d in enumerate(ivs): out.append(lemma(f"good_{i}",d,cstr))
chain=f"theorem goodQ_range (q : ℕ) (h1 : {2**lo} ≤ q) (h2 : q < {2**hi}) : GoodQ {cstr} q := by\n"
for i,d in enumerate(ivs[:-1]):
    chain+=f"  rcases lt_or_ge q {d['Qb']} with h | h1\n  · exact good_{i} q h1 h\n"
chain+=f"  exact good_{len(ivs)-1} q h1 h2\n"
out.append(chain)
out.append(f"end LLS.Iv{tag}\n")
print("\n".join(out))
