import json, sys, os
d=json.load(open(sys.argv[1])); W=int(sys.argv[3]); out=sys.argv[2]
ents=d['ents']
ents[-1]['Gn']=ents[-2]['Gn']; ents[-1]['en']=ents[-2]['en']; ents[-1]['r']=ents[-2]['r']
C1a,C1b,C2a,C2b,As=d['C']; GD=d['GD']
def ent(e): return f"⟨{e['N']}, {e['k']}, {e['cl']}, {e['cu']}, {e['j']}, {e['fl']}, {e['tg']}, {e['Gn']}, {e['en']}, {e['r']}⟩"
def ps(w,f): return sum(f(w[i],w[i+1]) for i in range(len(w)-1))
fs=dict(
 a1G=lambda e,f: e['Gn']*(f['N']-e['N']), a1e=lambda e,f: e['en']*(f['N']-e['N']),
 a2Gp=lambda e,f: e['Gn']*(f['N']-e['N'])*e['r'] if e['r']>=0 else 0,
 a2Gn=lambda e,f: 0 if e['r']>=0 else e['Gn']*(f['N']-e['N'])*(-e['r']),
 a2ep=lambda e,f: e['en']*(f['N']-e['N'])*e['r'] if e['r']>=0 else 0,
 a2en=lambda e,f: 0 if e['r']>=0 else e['en']*(f['N']-e['N'])*(-e['r']),
 tvG=lambda e,f: abs(f['Gn']-e['Gn']), tve=lambda e,f: abs(f['en']-e['en']))
keys=['a1G','a1e','a2Gp','a2Gn','a2ep','a2en','tvG','tve']
wins=[]; i=0
while i < len(ents)-1:
    wins.append(ents[i:i+W+1]); i+=W
n=len(wins)
vs=[]; tot={k:0 for k in keys}
for w in wins:
    v={k:ps(w,fs[k]) for k in keys}; vs.append(v)
    for k in keys: tot[k]+=v[k]
L=[]
L.append("import CramerCompute.CMSWindows\n")
L.append("/-! The glued cell list and its certified constants (generated by `scripts/cms_gen.py`). -/\n")
L.append("namespace CramerCompute.CMSData\n")
L.append("set_option maxRecDepth 100000 in")
L.append("/-- The windows with their claimed partial sums. -/")
L.append("def wv : List (List Ent × WSums) := [")
L.append(",\n".join(f"  (w{k:04d}, ⟨{', '.join(str(vs[k][kk]) for kk in keys)}⟩)" for k in range(n)))
L.append("]\n")
L.append("/-- Every window passes its check. -/")
L.append("def AllOK : List (List Ent × WSums) → Prop\n  | [] => True\n  | p :: l => winOK qs "+f"{GD} {C1a} {C1b} {C2a} {C2b}"+" p.1 p.2 = true ∧ AllOK l\n")
L.append("set_option maxRecDepth 100000 in")
L.append("theorem wv_ok : AllOK wv := ⟨"+", ".join(f"w{k:04d}_ok" for k in range(n))+", trivial⟩\n")
L.append("/-- Head and last entries. -/")
L.append("def HeadLast : List (List Ent) → Prop\n  | [] => True\n  | w :: l => (∃ a b : Ent, w.head? = some a ∧ w.getLast? = some b ∧ a.N < b.N) ∧ HeadLast l\n")
L.append("set_option maxRecDepth 100000 in")
L.append("theorem wv_hl : HeadLast (wv.map Prod.fst) := ⟨"+", ".join(f"⟨_, _, w{k:04d}_head, w{k:04d}_last, by decide⟩" for k in range(n))+", trivial⟩\n")
L.append("/-- Consecutive windows share an entry. -/")
L.append("def Links : List (List Ent) → Prop\n  | [] => True\n  | [_] => True\n  | w :: v :: l => w.getLast? = v.head? ∧ Links (v :: l)\n")
L.append("set_option maxRecDepth 100000 in")
L.append("theorem wv_links : Links (wv.map Prod.fst) := ⟨"+", ".join(f"(w{k:04d}_last).trans (w{k+1:04d}_head).symm" for k in range(n-1))+", trivial⟩\n")
for kk in keys:
    L.append(f"theorem wv_sum_{kk} : (wv.map (fun p => p.2.{kk})).sum = {tot[kk]} := by decide +kernel")
L.append("")
L.append(f"theorem w_first_head : w0000.head? = some {ent(wins[0][0])} := w0000_head")
L.append(f"theorem w_first_second : w0000.getD 1 default = {ent(wins[0][1])} := rfl")
L.append(f"theorem w_last_last : w{n-1:04d}.getLast? = some {ent(wins[-1][-1])} := w{n-1:04d}_last")
L.append(f"theorem w_first_len : 2 < w0000.length := by decide")
L.append("\nend CramerCompute.CMSData\n")
open(out,'w').write("\n".join(L))
print(n, tot)
