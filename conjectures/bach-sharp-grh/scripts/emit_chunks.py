"""Write the chunk modules BachSharp/Compute/*.lean. Run from the project root.

Each chunk is one `native_decide`; soundness: `BachSharp.Check.checkChunkC_sound` (large `q`,
under GRH) and `BachSharp.Check.checkSmall_sound` (small `q`, no GRH).
"""
large = [("L0", 1024, 10, "5 * 2 ^ 49", "2 ^ 100"), ("L1", 64, 0, "2 ^ 100", "2 ^ 7400")]
small = [("S0", "4", "2 ^ 14 - 4"), ("S1", "2 ^ 14", "2 ^ 14"), ("S2", "2 ^ 15", "2 ^ 15"),
         ("S3", "2 ^ 16", "2 ^ 16")]
for name, m, w, lo, hi in large:
    open(f"BachSharp/Compute/{name}.lean", "w").write(f"""import BachSharpCheck

/-! Chunk {name}: the GRH budget with constant `1657/1000` for `{lo} ≤ q < {hi}`.

Evaluated by `native_decide` (one auxiliary axiom trusting the compiled evaluation of the
core-Lean checker `BachSharpCheck`; soundness `BachSharp.Check.checkChunkC_sound`). Generated by
`scripts/emit_chunks.py`. -/

namespace BachSharp

theorem chunk_ok_{name} : BachSharp.Check.checkChunkC 1657 1000 {m} {w} ({lo}) ({hi}) = true := by
  native_decide

end BachSharp
""")
for name, lo, n in small:
    open(f"BachSharp/Compute/{name}.lean", "w").write(f"""import BachSharpCheck

/-! Chunk {name}: generation of `(ZMod q)ˣ` by the units `≤ ⌊1.657 (logLo q 64)²⌋` for
`{lo} ≤ q < {lo} + ({n})`, by breadth-first search (no GRH).

Evaluated by `native_decide` (one auxiliary axiom trusting the compiled evaluation of the
core-Lean checker `BachSharpCheck`; soundness `BachSharp.Check.checkSmall_sound`). Generated by
`scripts/emit_chunks.py`. -/

namespace BachSharp

theorem small_ok_{name} : BachSharp.Check.checkSmall ({lo}) ({n}) = true := by
  native_decide

end BachSharp
""")
