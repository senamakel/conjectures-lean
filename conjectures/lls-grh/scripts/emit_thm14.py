"""Emit LLS/Thm14/Cells.lean: the boxes for the two-variable condition of LLS Theorem 1.4.

Each leaf box [u1,u2] x [L1,L2] is checked here in exact rational arithmetic, exactly as Lean
checks it with `LLS.Thm14.cell_of`; internal nodes split on `u` or on `L`.
"""
from fractions import Fraction as F
import math, sys

LO = F(6931471803, 10**10)
HI = F(6931471808, 10**10)

def lg_lo(n):  # largest a with 2^a <= n^1024
    a = int(1024 * math.log2(n))
    while 2 ** (a + 1) <= n ** 1024: a += 1
    while 2 ** a > n ** 1024: a -= 1
    return a

def lg_hi(n):  # smallest c with n^1024 <= 2^c
    c = int(math.ceil(1024 * math.log2(n)))
    while n ** 1024 > 2 ** c: c += 1
    while c > 0 and n ** 1024 <= 2 ** (c - 1): c -= 1
    return c

def phi2(u1, L1, lam):
    return (F(6254, 1000) * lam + (6 * lam ** 2 + F(4586, 100) * lam + F(2125, 100)) / (L1 + 3)
            + (20 * lam ** 2 + F(180008, 10000) * lam + 3) / 31622 + F(58824, 100000) * lam ** 2 / u1)

def lit(q):
    q = F(q)
    return "(%d : ℝ)" % q.numerator if q.denominator == 1 else "(%d / %d : ℝ)" % (q.numerator, q.denominator)

def leaf_data(u1, u2, L1, L2):
    N1 = 9 if L1 < 10 else int(L1)
    a = lg_lo(N1); bl1 = F(a, 1024) * LO
    N2 = int(L2); c = lg_hi(N2); bh2 = F(c, 1024) * HI
    corner = u2 * N2 + 3 * (u2 + 2) + F(5, 2) * bh2 ** 2
    M = math.ceil(corner); k = lg_hi(M); lam2 = F(k, 1024) * HI
    if corner < 31622:
        kind = 'I'
    elif phi2(F(u1), F(L1), lam2) <= F(609, 1000) * u1 + F(158, 100) + F(5, 2) * bl1 ** 2:
        kind = 'II'
    else:
        kind = None
    return dict(N1=N1, a=a, N2=N2, c=c, M=M, k=k, kind=kind)

nodes = []  # (name, u1,u2,L1,L2, kind, data/split)
cnt = [0]
def rec(u1, u2, L1, L2, d=0):
    name = "n%d" % cnt[0]; cnt[0] += 1
    dat = leaf_data(u1, u2, L1, L2)
    if dat['kind']:
        nodes.append((name, u1, u2, L1, L2, 'leaf', dat)); return name
    if d > 40: raise Exception("fail %s" % ((u1, u2, L1, L2),))
    ru = math.log(u2 / u1); rL = math.log(math.log(L2) / math.log(float(L1))) * 3
    if ru >= rL and u2 > u1 + 1:
        m = round(math.sqrt(u1 * u2)); m = min(max(m, u1 + 1), u2 - 1)
        a = rec(u1, m, L1, L2, d + 1); b = rec(m, u2, L1, L2, d + 1)
        nodes.append((name, u1, u2, L1, L2, 'u', (m, a, b)))
    else:
        m = round(math.exp(math.sqrt(math.log(float(L1)) * math.log(L2))))
        if m <= L1 or m >= L2: m = (int(L1) + L2) // 2
        a = rec(u1, u2, L1, m, d + 1); b = rec(u1, u2, m, L2, d + 1)
        nodes.append((name, u1, u2, L1, L2, 'L', (m, a, b)))
    return name

UMAX, LMAX = 10 ** 5, 10 ** 30
root = rec(1, UMAX, F(99, 10), LMAX)

out = []
out.append("""import LLS.Thm14.CellCore

/-!
# Boxes for the two-variable condition, `1 ≤ u ≤ 10^5`, `9.9 ≤ L ≤ 10^30`

Generated by `scripts/emit_thm14.py`. A leaf either has `Bf < 31622` at its upper corner (no
point of it is in the range `Bf ≥ 31622`), or satisfies `LLS.Thm14.cell_of` at its corners.
%d nodes.
-/

set_option exponentiation.threshold 2048

namespace LLS.Thm14.Cells
open LLS.Thm14
""" % len(nodes))
HYP = "(u L : ℝ) (h1 : %s ≤ u) (h2 : u ≤ %s) (h3 : %s ≤ L) (h4 : L ≤ %s) (hB : 31622 ≤ Bf u L) :\n    Phi2 u L (Real.log (Bf u L)) ≤ 0.609 * u + 1.58 + 5 / 2 * Real.log L ^ 2"
for (name, u1, u2, L1, L2, typ, x) in nodes:
    hyp = HYP % (lit(u1), lit(u2), lit(L1), lit(L2))
    if typ == 'leaf':
        d = x
        chk = "(Or.inl (by norm_num))" if d['kind'] == 'I' else "(Or.inr (by unfold Phi2; norm_num))"
        out.append("""theorem %s %s := by
  have hbl := log_ge_nat (y := L) (X := %d) (k := %d) (by push_cast; linarith) (by decide +kernel) (by norm_num)
  have hbh := log_le_nat (y := L) (X := %d) (k := %d) (by linarith) (by push_cast; linarith) (by decide +kernel)
  have hbl0 : (0 : ℝ) ≤ (%d : ℕ) / 1024 * 0.6931471803 := by positivity
  refine cell_of %s %s %s %s _ _ ((%d : ℕ) / 1024 * 0.6931471808) (by norm_num) (by norm_num)
    h1 h2 h3 h4 hbl hbl0 hbh (fun hB' => lam_of %s %s _ %d %d h2 h4 (by linarith) (by linarith)
      (hbl0.trans hbl) hbh (by norm_num) (by decide +kernel) hB') %s hB
""" % (name, hyp, d['N1'], d['a'], d['N2'], d['c'], d['a'], lit(u1), lit(u2), lit(L1), lit(L2), d['k'],
       lit(u2), lit(L2), d['M'], d['k'], chk))
    else:
        m, a, b = x
        var = 'u' if typ == 'u' else 'L'
        if typ == 'u':
            body = "  rcases le_total u %s with h | h\n  · exact %s u L h1 h h3 h4 hB\n  · exact %s u L h h2 h3 h4 hB\n" % (lit(m), a, b)
        else:
            body = "  rcases le_total L %s with h | h\n  · exact %s u L h1 h2 h3 h hB\n  · exact %s u L h1 h2 h h4 hB\n" % (lit(m), a, b)
        out.append("theorem %s %s := by\n%s" % (name, hyp, body))
out.append("""/-- The boxes cover `1 ≤ u ≤ 10^5`, `9.9 ≤ L ≤ 10^30`. -/
theorem box_all (u L : ℝ) (h1 : 1 ≤ u) (h2 : u ≤ 100000) (h3 : 99 / 10 ≤ L)
    (h4 : L ≤ 1000000000000000000000000000000) (hB : 31622 ≤ Bf u L) :
    Phi2 u L (Real.log (Bf u L)) ≤ 0.609 * u + 1.58 + 5 / 2 * Real.log L ^ 2 :=
  %s u L (by exact_mod_cast h1) (by exact_mod_cast h2) h3 (by exact_mod_cast h4) hB

end LLS.Thm14.Cells
""" % root)
open(sys.argv[1], 'w').write("\n".join(out))
print(len(nodes), sum(1 for n in nodes if n[5]=='leaf'))
