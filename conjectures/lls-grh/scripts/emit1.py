import sys
from gen1 import *
from emit import q
lo=int(sys.argv[1]); hi=int(sys.argv[2])
ivs,fail=plan1(2**lo,2**hi)
assert fail is None
out=[f"""import LLS.Numerics.Prime

/-!
# Certified intervals for prime moduli, `c = 1`: every `2^{lo} ≤ q < 2^{hi}` is `GoodP 1`

Generated by `scripts/emit1.py {lo} {hi}`; {len(ivs)} intervals.
-/

set_option exponentiation.threshold 1024

namespace LLS.IvP
open LLS
"""]
for i,d in enumerate(ivs):
    out.append(f"""theorem good_{i} (q : ℕ) (h1 : {d['Qa']} ≤ q) (h2 : q < {d['Qb']}) : GoodP 1 q :=
  goodP_of_data q {d['Qa']} {d['Qb']} {d['ka']} {d['kb']} {d['x']} {q(d['s1'])} {q(d['s2'])} {d['k1']} {d['k2']} h1 h2
    (by decide +kernel) (by decide +kernel) (by decide +kernel) (by decide +kernel) (by norm_num) (by norm_num) (by norm_num) (by norm_num) (by norm_num)
    (by norm_num [Side1OK, iEs])
    (by norm_num [Phi1Lo, iK₁, iK₂, ik₂, iEs])
""")
chain=f"theorem goodP_range (q : ℕ) (h1 : 2 ^ {lo} ≤ q) (h2 : q < 2 ^ {hi}) : GoodP 1 q := by\n  norm_num at h1 h2\n"
for i,d in enumerate(ivs[:-1]):
    chain+=f"  rcases lt_or_ge q {d['Qb']} with h | h1\n  · exact good_{i} q h1 h\n"
chain+=f"  exact good_{len(ivs)-1} q h1 h2\n"
out.append(chain); out.append("end LLS.IvP\n")
print("\n".join(out))
