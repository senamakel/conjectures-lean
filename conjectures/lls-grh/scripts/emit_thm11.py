    d=data(b)
    hdr=f"theorem {name}_{i} (x : ℕ) (h1 : {b['Xa']} ≤ x) (h2 : x < {b['Xb']}) :"
    ib=f"  have B := inBox_of_data x {d} h1 h2.le (by decide +kernel) (by decide +kernel)\n    (by norm_num) (by norm_num) (by norm_num) (by norm_num) (by norm_num) (by norm_num) (by norm_num)\n"
    if kind=='F1s':
        return hdr+" 0 < F1 x := by\n"+ib+"  refine lt_of_lt_of_le ?_ (F1_ge B (PcF_sub_small (by omega)))\n  norm_num [F1Lo, min_def]\n"
    if kind=='F1':
        return hdr+" 0 < F1 x := by\n"+ib+"  refine lt_of_lt_of_le ?_ (F1_ge B (PcF_sub_big B (by norm_num)))\n  norm_num [F1Lo, min_def]\n"
    if kind=='F2a':
        return hdr+" 0 < F2 x 8 := by\n"+ib+"  refine lt_of_lt_of_le ?_ (F2a_ge B (by norm_num [F2aSide]))\n  norm_num [F2aLo]\n"
    if kind=='F2b':
        return hdr+" 0 < F2 x (nu x - 3 - 2 * Real.log 8) := by\n"+ib+"  refine lt_of_lt_of_le ?_ (F2b_ge B (by norm_num))\n  norm_num [F2bLo, min_def]\n"
    if kind=='R5':
        return hdr+" R5OK x := by\n"+ib+"  exact R5_of B (by norm_num)\n"
