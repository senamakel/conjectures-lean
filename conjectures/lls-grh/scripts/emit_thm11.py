import sys; sys.path.insert(0, sys.argv[1])
from thm11_lo import *
XT = 10**16
def side_ok(name, b):
    Xa,sa,sb,la,lb=b['Xa'],b['sa'],b['sb'],b['la'],b['lb']
    if la < 4 or sa < 8: return False
    if name=='F2a':
        c=common(Xa,sa,sb,la,lb)
        return c['mEsh']>=0 and sa+c['dlo']>=0 and h2hi/la<=1
    if name=='F2b':
        return sa > c2hi
    return True
def val(name,b,big):
    a=(b['Xa'],b['sa'],b['sb'],b['la'],b['lb'])
    if name=='F1': return F1Lo(*a,big=big)[0]
    if name=='F2a': return F2aLo(*a)[0]
    if name=='F2b': return F2bLo(*a)[0]
    if name=='R5': return R5Lo(*a)[0]
def plan(name, X0, X1, big=True):
    out=[]; X=X0
    while X < X1:
        best=None
        for r in [2**20,2**10,64,16,8,4,3,2,1.6,1.4,1.25,1.15,1.1,1.05,1.02,1.01,1.0]:
            Xb=min(X1, max(X+1,int(X*r)))
            b=box(X,Xb)
            if side_ok(name,b) and val(name,b,big)>0: best=b; break
        if best is None: raise SystemExit("FAIL %s %d"%(name,X))
        out.append(best); X=best['Xb']
    return out
def q(fr): return "(%d / %d : ℝ)"%(fr.numerator,fr.denominator) if fr.denominator!=1 else "(%d : ℝ)"%fr.numerator
def data(b):
    return f"{b['Xa']} {b['Xb']} {b['ka']} {b['kb']} {q(b['sa'])} {q(b['sb'])}"
boxes = {'F1s': plan('F1',64,100,big=False), 'F1': plan('F1',100,XT), 'F2a': plan('F2a',228,XT),
         'F2b': plan('F2b',228,XT), 'R5': plan('R5',64,XT)}
for k,v in boxes.items(): print('--',k,len(v), file=sys.stderr)
