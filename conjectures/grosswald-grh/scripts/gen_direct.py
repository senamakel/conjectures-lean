#!/usr/bin/env python3
"""Generate the native_decide chunks for the finite range 411 <= p < END (Grosswald/Direct/).

Region A: segsOk 50 411 1000 and segsOk 1000 100411 49950 cover [411, 100000411).
Region B: NB chunks of S segments of L odd numbers each, starting at 100000411.
Groups of G chunks are glued with segsOk_append; Main glues the groups.
"""
import os, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'Grosswald', 'Direct')
L, S, NB, G = 20000000, 100, 2500, 50
B0 = 100000411
STEP = 2 * L * S
END = B0 + NB * STEP
HDR = '''import GrosswaldCompute.Seg

/-! Verified computation (`native_decide`): one chunk of the finite range. Soundness:
`Grosswald.Direct.range_sound`. Generated by `scripts/gen_direct.py`. -/
'''
def w(path, s):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if not os.path.exists(path) or open(path).read() != s:
        open(path, 'w').write(s)
w(f'{ROOT}/Run/A.lean', HDR + '''
namespace Grosswald.Direct.Run
open GrosswaldCompute
theorem a1 : segsOk 50 411 1000 = true := by native_decide
theorem a2 : segsOk 1000 100411 49950 = true := by native_decide
end Grosswald.Direct.Run
''')
for k in range(NB):
    a = B0 + k * STEP
    w(f'{ROOT}/Run/B{k:04d}.lean', HDR + f'''
namespace Grosswald.Direct.Run
theorem b{k:04d} : GrosswaldCompute.segsOk {L} {a} {S} = true := by native_decide
end Grosswald.Direct.Run
''')
ng = NB // G
for g in range(ng):
    ks = range(g * G, (g + 1) * G)
    imps = ''.join(f'import Grosswald.Direct.Run.B{k:04d}\n' for k in ks)
    lines = []
    last = ks[-1]
    lines.append(f'  have h{last:04d} : segsOk {L} {B0 + last*STEP} {S} = true := Run.b{last:04d}')
    for k in reversed(ks[:-1]):
        n = (last - k + 1) * S
        lines.append(f'  have h{k:04d} : segsOk {L} {B0 + k*STEP} {n} = true :=\n'
                     f'    segsOk_append {S} _ _ _ Run.b{k:04d} h{k+1:04d} (by norm_num)')
    w(f'{ROOT}/Group/G{g:02d}.lean', 'import Grosswald.Direct.Sound\n' + imps + f'''
namespace Grosswald.Direct
open GrosswaldCompute
theorem g{g:02d} : segsOk {L} {B0 + g*G*STEP} {G*S} = true := by
''' + '\n'.join(lines) + f'\n  exact h{ks[0]:04d}\nend Grosswald.Direct\n')
imps = ''.join(f'import Grosswald.Direct.Group.G{g:02d}\n' for g in range(ng))
lines = [f'  have h{ng-1:02d} : segsOk {L} {B0 + (ng-1)*G*STEP} {G*S} = g{ng-1:02d}']
lines[0] = f'  have h{ng-1:02d} : segsOk {L} {B0 + (ng-1)*G*STEP} {G*S} = true := g{ng-1:02d}'
for g in reversed(range(ng - 1)):
    lines.append(f'  have h{g:02d} : segsOk {L} {B0 + g*G*STEP} {(ng-g)*G*S} = true :=\n'
                 f'    segsOk_append {G*S} _ _ _ g{g:02d} h{g+1:02d} (by norm_num)')
w(f'{ROOT}/Main.lean', 'import Grosswald.Direct.Sound\nimport Grosswald.Direct.Run.A\n' + imps + f'''
/-!
# The finite range `409 < p < {END}`

Every prime `p` with `409 < p < {END}` has a primitive root `g < √p - 2`: chunks
`Run.a1`, `Run.a2` ([411, {B0})) and `Run.b0000` … `Run.b{NB-1:04d}` ([{B0}, {END})), each a
`native_decide` evaluation of `GrosswaldCompute.segsOk`, glued by `segsOk_append` and read off by
`range_sound`. Generated by `scripts/gen_direct.py`.
-/

namespace Grosswald.Direct
open GrosswaldCompute

/-- The end of the directly checked range. -/
def directEnd : ℕ := {END}

theorem segsB : segsOk {L} {B0} {NB*S} = true := by
''' + '\n'.join(lines) + f'''
  exact h00

theorem direct_range : ∀ p : ℕ, p.Prime → 409 < p → p < directEnd →
    Grosswald.HasSmallPrimitiveRoot p := by
  intro p hp h1 h2
  unfold directEnd at h2
  have h410 : p ≠ 410 := by rintro rfl; norm_num at hp
  by_cases hA1 : p < 100411
  · exact range_sound Run.a1 (by norm_num) (by norm_num) (by norm_num) p hp (by omega) (by omega)
  by_cases hA2 : p < {B0}
  · exact range_sound Run.a2 (by norm_num) (by norm_num) (by norm_num) p hp (by omega) (by omega)
  exact range_sound segsB (by norm_num) (by norm_num) (by norm_num) p hp (by omega) (by omega)

end Grosswald.Direct
''')
print('END', END)
